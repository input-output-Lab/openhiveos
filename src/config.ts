import { z } from 'zod'

// ---------------------------------------------------------------------------
// Environment schema — validated at process startup.
// Any missing required variable throws immediately and prevents the MCP server
// from starting in a degraded state.
//
// ARCH-021 (gateway mode): when GATEWAY_MODE=true the subprocess is spawned
// by the mcp-gateway. Identity is resolved per-call from __agentSlug injected
// into tool arguments by the gateway — AGENT_TOKEN is not required in this mode.
// ---------------------------------------------------------------------------

const isGatewayMode = process.env['GATEWAY_MODE'] === 'true'

const ConfigSchema = z.object({
  DATABASE_URL: z.string().min(1),
  GEMINI_API_KEY: z.string().min(1),
  // Process-level agent identity — ARCH-008 Decision 7
  // Format: <32-hex-salt>.<64-hex-secret>  Generated by scripts/provision-agent-token.ts
  // Regex validated here (SHOULD-FIX-1 from S2-02): fail at Step 1 with a
  // clear error rather than silently passing a malformed token to Step 4.
  // ARCH-021: optional in GATEWAY_MODE — identity comes per-call, not at boot.
  AGENT_TOKEN: isGatewayMode
    ? z.string().optional()
    : z.string().regex(
        /^[\da-f]{32}\.[\da-f]{64}$/i,
        'AGENT_TOKEN must be <32-hex-salt>.<64-hex-secret> — run scripts/provision-agent-token.ts',
      ),
  // ARCH-021: when true, identity is resolved per-call from __agentSlug (gateway-injected).
  GATEWAY_MODE: z.enum(['true', 'false']).optional().transform((v) => v === 'true'),
  // HTTP port for the health endpoint (separate from MCP stdio transport)
  HEALTH_PORT: z.coerce.number().int().positive().default(3000),
  // Squad API integration — ARCH-015 (report_usage utility)
  // URL to the squad-api (e.g., http://localhost:3005)
  SQUAD_API_URL: z.string().url().default('http://localhost:3005'),
  // Ingestion token for POST /internal/usage — ARCH-015 SEC-C1.
  // Must match OPENHIVEOS_INGESTION_TOKEN in squad-api/.env
  // Generated: node -e "console.log(require('crypto').randomBytes(32).toString('hex'))"
  OPENHIVEOS_INGESTION_TOKEN: z.string().min(64).optional(),
  // Ethos Seal — ARCH-013 Step 3.5 boot check (checkEthosSeal).
  // ETHOS_SEAL_SECRET is NOT here — the MCP server never re-derives the HMAC.
  // It only compares the stored DB signature against the exported file signature.
  ETHOS_SEAL_PATH: z.string().min(1).default('./ethos.seal.json'),
  // One Seal — ARCH-025 Step 3.6 boot check (checkOneSeal).
  // ONE_SEAL_SECRET is NOT here — the MCP server never re-derives the HMAC.
  // It only compares the stored DB signature against the exported file signature.
  ONE_SEAL_PATH: z.string().min(1).default('./one.seal.json'),
})

export type Config = z.infer<typeof ConfigSchema>

const result = ConfigSchema.safeParse(process.env)

if (!result.success) {
  const missing = result.error.issues
    .map((issue) => issue.path.join('.'))
    .join(', ')
  throw new Error(
    `[config] Missing or invalid required environment variables: ${missing}`,
  )
}

export const config: Config = result.data
